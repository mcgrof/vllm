class TestProviderStats:

    def test_stats_after_registration(self) -> None:
        path = _require(PERK_PRIOR)
        provider = CartridgeKRIProvider()
        provider.register_prior(prefix_hash="abc123", prior_path=path)
        provider.register_prior(
            prefix_hash="def456",
            prior_path=path,
            prior_type="kri_g",
        )
        stats = provider.stats()
        assert stats["num_priors"] == 2
        assert sorted(stats["prefix_hashes"]) == ["abc123", "def456"]
        assert stats["prior_types"] == ["kri_g"]
